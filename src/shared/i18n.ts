const TABLE: Record<Locale, Strings> = { fr, en, de, 'pt-BR': ptBR };

export const LOCALES: readonly Locale[] = ['fr', 'en', 'de', 'pt-BR'];

export const LANGUAGE_NAMES: Record<Locale, string> = {
  fr: 'Français',
  en: 'English',
  de: 'Deutsch',
  'pt-BR': 'Português (Brasil)',
};

export function pickLocale(systemLocale: string): Locale {
  const lang = systemLocale.toLowerCase();
  if (lang.startsWith('fr')) return 'fr';
  if (lang.startsWith('de')) return 'de';
  if (lang.startsWith('pt')) return 'pt-BR';
  return 'en';
}

export function resolveLocale(setting: string, systemLocale: string): Locale {
  return (LOCALES as readonly string[]).includes(setting) ? (setting as Locale) : pickLocale(systemLocale);
}

export function t(locale: Locale, key: StringKey, vars?: Record<string, string | number>): string {
  let text = TABLE[locale][key] ?? TABLE.en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}

